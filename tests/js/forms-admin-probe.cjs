/* Exercise Turnstile visibility, SMTP settings, secret races and save-before-test without a browser. */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const tick = () => new Promise(resolve => setImmediate(resolve));
async function scenario() {
  const fields = {};
  for (const [name, value] of Object.entries({turnstile_site_key:'',turnstile_secret_key:'',slack_webhook_url:'',mailerlite_api_key:'',smtp_host:'smtp.example.org',smtp_port:'587',smtp_encryption:'tls',smtp_username:'forms@example.org',smtp_password:'old-password',smtp_from_email:'forms@example.org',smtp_from_name:'Forms'})) fields[name] = {name, value, type: name === 'smtp_encryption' ? 'select-one' : 'text', placeholder:''};
  for (const name of ['turnstile_enabled','slack_enabled','smtp_enabled','smtp_auth','clear_smtp_password','mailerlite_enabled','clear_mailerlite_api_key']) fields[name] = {name,type:'checkbox',checked:name.startsWith('smtp_')};
  const previewValues = {}, stylePreview = {style:{setProperty(name,value){previewValues[name]=value;}}};
  const styleFields = [];
  for (const [name,value,variable,unit] of [['style_border_width','1','--erankly-form-border-width','px'],['style_background','#ffffff','--erankly-form-background',''],['style_padding_vertical','12','--erankly-form-padding-vertical','px']]) {
    const field = {name,value,type:unit?'number':'color',validity:{valid:true},dataset:{styleVariable:variable,styleUnit:unit,styleDefault:value}};
    fields[name] = field; styleFields.push(field);
  }
  const listeners = {}, status = {textContent:''}, smtpFields = {hidden:false}, turnstileFields = {hidden:false}, slackFields = {hidden:false}, mailerliteFields = {hidden:false}, buttons = {};
  const form = {elements:fields,reportValidity(){return styleFields.every(field=>field.validity.valid);},querySelectorAll(selector) { if (selector === '[data-style-variable]') return styleFields; if (selector === '[data-style-value]') return []; assert.equal(selector,'input, select'); return [...Object.values(fields),{name:'',value:'shortcode'},{name:'',value:'preview'}]; },addEventListener(type, callback) { listeners[type] = callback; }};
  for (const channel of ['smtp','slack','mailerlite']) buttons[channel] = {disabled:false,addEventListener(type, callback) { this.click = () => callback({target:this}); }};
  const resetStyle = {addEventListener(type,callback){this.click=callback;}};
  const requests = [], timers = new Map(); let nextTimer = 0;
  vm.runInNewContext(fs.readFileSync(require('node:path').resolve(__dirname,'../../assets/js/forms-admin.js'),'utf8'), {
    document:{getElementById(id) { if (id === 'erankly-forms-settings') return form; if (id === 'erankly-forms-admin-status') return status; if (id === 'erankly-forms-smtp-fields') return smtpFields; if (id === 'erankly-forms-turnstile-fields') return turnstileFields; if (id === 'erankly-forms-slack-fields') return slackFields; if (id === 'erankly-forms-mailerlite-fields') return mailerliteFields; if (id === 'erankly-forms-style-preview') return stylePreview; if (id === 'erankly-forms-style-reset') return resetStyle; return buttons[id.includes('smtp')?'smtp':id.includes('mailerlite')?'mailerlite':'slack']; },querySelectorAll(){return [];}},
    wp:{i18n:{__:s=>s},apiFetch(options) { return new Promise((resolve,reject)=>requests.push({options,resolve,reject})); }},
    setTimeout(callback){const id=++nextTimer;timers.set(id,callback);return id;},clearTimeout(id){timers.delete(id);}
  });
  assert.equal(turnstileFields.hidden,true);
  assert.equal(slackFields.hidden,true);
  assert.equal(previewValues['--erankly-form-border-width'],'1px');
  assert.equal(previewValues['--erankly-form-padding-vertical'],'12px');
  listeners.input(); [...timers.values()][0](); timers.clear();
  assert.equal(requests.length,1);
  assert.equal(requests[0].options.data.smtp_encryption,'tls');
  assert.equal(requests[0].options.data.style_background,'#ffffff');
  assert.ok(!Object.hasOwn(requests[0].options.data,''));
  assert.equal(requests[0].options.data.turnstile_enabled,false);
  assert.ok(!Object.hasOwn(requests[0].options.data,'turnstile_secret_key'));
  assert.ok(!Object.hasOwn(requests[0].options.data,'turnstile_site_key'));
  assert.equal(requests[0].options.data.slack_enabled,false);
  assert.ok(!Object.hasOwn(requests[0].options.data,'slack_webhook_url'));
  fields.smtp_password.value = 'new-password'; fields.smtp_port.value = '465'; fields.smtp_encryption.value = 'ssl'; listeners.input();
  const clicked = buttons.smtp.click(); assert.equal(buttons.smtp.disabled,true);
  requests[0].resolve({smtp_password_configured:true}); await tick();
  assert.equal(fields.smtp_password.value,'new-password'); assert.equal(requests.length,2);
  assert.equal(requests[1].options.data.smtp_encryption,'ssl'); assert.equal(requests[1].options.data.smtp_password,'new-password');
  requests[1].resolve({smtp_password_configured:true}); await tick();
  assert.equal(fields.smtp_password.value,''); assert.equal(requests.length,3);
  assert.equal(requests[2].options.path,'/erankly/v1/forms/smtp-test');
  requests[2].resolve({message:'Accepted'}); await clicked;
  assert.equal(status.textContent,'Accepted'); assert.equal(buttons.smtp.disabled,false);
  const failed = buttons.smtp.click(); requests[3].reject({message:'Invalid configuration'}); await failed;
  assert.equal(requests.length,4); assert.equal(status.textContent,'Invalid configuration'); assert.equal(buttons.smtp.disabled,false);
  fields.clear_smtp_password.checked = true;
  fields.slack_enabled.checked = true; fields.slack_webhook_url.value = 'https://hooks.slack.com/services/T/B/TEST'; listeners.input();
  assert.equal(slackFields.hidden,false);
  const removal = buttons.slack.click(); assert.equal(requests[4].options.data.clear_smtp_password,true);
  assert.equal(requests[4].options.data.slack_enabled,true);
  assert.equal(requests[4].options.data.slack_webhook_url,'https://hooks.slack.com/services/T/B/TEST');
  requests[4].resolve({smtp_password_configured:false,slack_configured:true}); await tick();
  assert.equal(fields.slack_webhook_url.value,'');
  assert.equal(fields.slack_webhook_url.placeholder,'Configured — enter a replacement');
  assert.equal(fields.clear_smtp_password.checked,false); assert.equal(fields.smtp_password.placeholder,'');
  assert.equal(requests[5].options.path,'/erankly/v1/forms/slack-test'); requests[5].resolve({message:'Slack test'}); await removal;
  fields.turnstile_enabled.checked = true;
  fields.turnstile_site_key.value = 'valid-site-key'; fields.turnstile_secret_key.value = 'valid-secret'; listeners.input();
  assert.equal(turnstileFields.hidden,false);
  listeners.submit({preventDefault(){}});
  assert.equal(requests[6].options.data.turnstile_secret_key,'valid-secret');
  requests[6].resolve({turnstile_secret_configured:true}); await tick();
  assert.equal(fields.turnstile_secret_key.value,'');
  assert.equal(fields.turnstile_secret_key.placeholder,'Configured — enter a replacement');
  fields.turnstile_secret_key.value = 'stale-secret'; fields.turnstile_enabled.checked = false; listeners.input();
  assert.equal(turnstileFields.hidden,true);
  listeners.submit({preventDefault(){}});
  assert.equal(requests[7].options.data.turnstile_enabled,false);
  assert.ok(!Object.hasOwn(requests[7].options.data,'turnstile_secret_key'));
  requests[7].resolve({turnstile_secret_configured:false}); await tick();
  assert.equal(fields.turnstile_secret_key.value,''); assert.equal(fields.turnstile_secret_key.placeholder,'');
  assert.equal(fields.turnstile_site_key.value,'valid-site-key');
  // A new key entered while a disable request is pending must survive its response.
  listeners.submit({preventDefault(){}});
  fields.turnstile_enabled.checked = true; fields.turnstile_secret_key.value = 'replacement-secret'; listeners.input();
  listeners.submit({preventDefault(){}});
  requests[8].resolve({turnstile_secret_configured:false}); await tick();
  assert.equal(fields.turnstile_secret_key.value,'replacement-secret');
  assert.equal(requests[9].options.data.turnstile_enabled,true);
  assert.equal(requests[9].options.data.turnstile_secret_key,'replacement-secret');
  requests[9].resolve({turnstile_secret_configured:true}); await tick();
  assert.equal(fields.turnstile_secret_key.value,''); assert.equal(turnstileFields.hidden,false);
  fields.slack_webhook_url.value = 'stale-webhook'; fields.slack_enabled.checked = false; listeners.input();
  assert.equal(slackFields.hidden,true); listeners.submit({preventDefault(){}});
  assert.equal(requests[10].options.data.slack_enabled,false);
  assert.ok(!Object.hasOwn(requests[10].options.data,'slack_webhook_url'));
  requests[10].resolve({slack_configured:false}); await tick();
  assert.equal(fields.slack_webhook_url.value,''); assert.equal(fields.slack_webhook_url.placeholder,'');
  // A replacement webhook entered during a disable request survives until the next save.
  listeners.submit({preventDefault(){}});
  fields.slack_enabled.checked = true; fields.slack_webhook_url.value = 'https://hooks.slack.com/services/T/B/NEW'; listeners.input();
  listeners.submit({preventDefault(){}});
  requests[11].resolve({slack_configured:false}); await tick();
  assert.equal(fields.slack_webhook_url.value,'https://hooks.slack.com/services/T/B/NEW');
  assert.equal(requests[12].options.data.slack_enabled,true);
  assert.equal(requests[12].options.data.slack_webhook_url,'https://hooks.slack.com/services/T/B/NEW');
  requests[12].resolve({slack_configured:true}); await tick();
  assert.equal(fields.slack_webhook_url.value,''); assert.equal(slackFields.hidden,false);
  // Disabling Slack while the save-before-test is pending cancels the test message.
  const cancelled = buttons.slack.click();
  fields.slack_enabled.checked = false; listeners.input(); listeners.submit({preventDefault(){}});
  requests[13].resolve({slack_configured:true}); await tick();
  requests[14].resolve({slack_configured:false}); await cancelled;
  assert.equal(requests.length,15); assert.equal(buttons.slack.disabled,false); assert.equal(slackFields.hidden,true);
  fields.style_border_width.value = '3'; fields.style_background.value = '#e2e8f0'; fields.style_padding_vertical.value = '20'; listeners.input();
  assert.equal(previewValues['--erankly-form-border-width'],'3px');
  assert.equal(previewValues['--erankly-form-background'],'#e2e8f0');
  assert.equal(previewValues['--erankly-form-padding-vertical'],'20px');
  listeners.submit({preventDefault(){}});
  assert.equal(requests[15].options.data.style_border_width,'3');
  resetStyle.click();
  assert.equal(previewValues['--erankly-form-border-width'],'1px');
  requests[15].resolve({}); await tick();
  assert.equal(requests[16].options.data.style_border_width,'1');
  assert.equal(requests[16].options.data.style_background,'#ffffff');
  assert.equal(requests[16].options.data.style_padding_vertical,'12');
  requests[16].resolve({}); await tick();
  fields.style_border_width.value = '-1'; fields.style_border_width.validity.valid = false; listeners.input();
  assert.equal(previewValues['--erankly-form-border-width'],'1px');
  listeners.submit({preventDefault(){}}); await tick();
  assert.equal(requests.length,17,'Invalid sizes must not be posted');
  fields.style_border_width.value = '1'; fields.style_border_width.validity.valid = true;
  fields.mailerlite_enabled.checked = true; fields.mailerlite_api_key.value = 'original-mailerlite-api-key'; listeners.input();
  assert.equal(mailerliteFields.hidden,false);
  const connection = buttons.mailerlite.click();
  assert.equal(requests[17].options.data.mailerlite_api_key,'original-mailerlite-api-key');
  fields.mailerlite_api_key.value = 'replacement-mailerlite-api-key'; listeners.input(); listeners.submit({preventDefault(){}});
  requests[17].resolve({mailerlite_api_key_configured:true}); await tick();
  assert.equal(fields.mailerlite_api_key.value,'replacement-mailerlite-api-key');
  assert.equal(requests[18].options.data.mailerlite_api_key,'replacement-mailerlite-api-key');
  requests[18].resolve({mailerlite_api_key_configured:true}); await tick();
  assert.equal(fields.mailerlite_api_key.value,'');
  assert.equal(requests[19].options.path,'/erankly/v1/forms/mailerlite-test');
  requests[19].resolve({message:'Connected'}); await connection;
  assert.equal(buttons.mailerlite.disabled,false); assert.equal(status.textContent,'Connected');
  fields.clear_mailerlite_api_key.checked = true; listeners.submit({preventDefault(){}});
  requests[20].resolve({mailerlite_api_key_configured:false,mailerlite_enabled:false}); await tick();
  assert.equal(fields.mailerlite_enabled.checked,false); assert.equal(mailerliteFields.hidden,true);
  assert.equal(fields.clear_mailerlite_api_key.checked,false);
  console.log('Forms admin probe passed: global style preview/reset, MailerLite connection/key handling, Turnstile/Slack visibility, SMTP saves, secret races and test ordering.');
}
scenario().catch(error=>{console.error(error);process.exitCode=1;});
